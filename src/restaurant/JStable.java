public void loadTable() {

        model.setRowCount(0);

        try {
            Connection con = DBConnection.getConnection();
            Statement st = con.createStatement();
            ResultSet rs = st.executeQuery("SELECT Tableno, Capacity, Customer,Status FROM JStable ORDER BY Tableno");

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("Tableno"),
                    rs.getInt("Capacity"),
                    rs.getString("Customer"),
                    rs.getString("Status")
                });
            }

            rs.close();
            st.close();
            con.close();

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Error loading data: " + e.getMessage());
        }
    }
