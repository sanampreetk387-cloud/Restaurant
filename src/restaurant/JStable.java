    private void UpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_UpdateActionPerformed
        // TODO add your handling code here:
         int row = Ttable.getSelectedRow();

        if (row == -1) {

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Select a row first.");

            return;
        }
        try {
         int tableno=Integer.parseInt(Tableno.getText().trim());
            String customer = Customer.getText().trim();
            String status=Status.getSelectedItem().toString().trim();
            int capacity = Integer.parseInt(Capacity.getText().trim());
            
          if (customer.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Customer cannot be empty.");
                return;
            }
          int selectedTableno = (int) model.getValueAt(row, 0);
            Connection con = DBConnection.getConnection();
            PreparedStatement ps = con.prepareStatement(
                "UPDATE JStable SET Tableno = ?, Capacity= ?, Customer= ?,Status=? WHERE Tableno = ?");
            ps.setInt(1, tableno);
            ps.setInt(2, capacity);
            ps.setString(3,customer);
          
            ps.setString(4, status);
            ps.setInt(5,selectedTableno);
            int rows = ps.executeUpdate();
            ps.close();
            con.close();
          
          
          
           if (rows == 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "No record found to update.");
            } else {
                loadTable();
                clearFields();
            }

        } catch (Exception e) {

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Error updating record: " + e.getMessage());

        }
    }//GEN-LAST:event_UpdateActionPerformed

    private void DeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteActionPerformed
        // TODO add your handling code here:
         int row = Ttable.getSelectedRow();

        if (row == -1) {

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Select a row first.");

            return;
        }

        int confirm = javax.swing.JOptionPane.showConfirmDialog(this,
                "Are you sure you want to delete this record?",
                "Confirm Delete", javax.swing.JOptionPane.YES_NO_OPTION);

        if (confirm != javax.swing.JOptionPane.YES_OPTION) {
            return;
        }

        try {

            // Use the roll_no of the selected row to identify the record
            int selectedTableno = (int) model.getValueAt(row, 0);

            Connection con = DBConnection.getConnection();
            PreparedStatement ps = con.prepareStatement(
                "DELETE FROM JStable WHERE Tableno = ?");
            ps.setInt(1, selectedTableno);
            ps.executeUpdate();
        loadTable();

        clearFields();
    }                                      
catch (Exception e) {

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Error deleting record: " + e.getMessage());

        } 
    }//GEN-LAST:event_DeleteActionPerformed
