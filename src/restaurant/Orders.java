    private void DeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteActionPerformed
        // TODO add your handling code here:
        int row = Otable.getSelectedRow();

        if (row == -1) {

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Select a row first.");

            return;
        }
 int confirm = javax.swing.JOptionPane.showConfirmDialog(this,
                "Are you sure you want to delete this record?",
                "Confirm Delete", javax.swing.JOptionPane.YES_NO_OPTION);

        if (confirm != javax.swing.JOptionPane.YES_OPTION) {
            return;
        }

        try {

            // Use the roll_no of the selected row to identify the record
            int selectedID = (int) model.getValueAt(row, 0);

            Connection con = DBConnection.getConnection();
            PreparedStatement ps = con.prepareStatement(
                "DELETE FROM Orders WHERE ID = ?");
            ps.setInt(1, selectedID);
            ps.executeUpdate();
            ps.close();
            con.close();
       

        loadTable();
        clearFields();
    }                                      
catch (Exception e) {

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Error deleting record: " + e.getMessage());

        }
    }//GEN-LAST:event_DeleteActionPerformed

    private void AddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AddActionPerformed
        // TODO add your handling code here:
          try {
            int item  = Integer.parseInt(Item.getText().trim());
            int tableno= Integer.parseInt(Tableno.getText().trim());

            Connection con = DBConnection.getConnection();
            PreparedStatement ps = con.prepareStatement(
                "INSERT INTO Orders (Item,Tableno) VALUES (?,?)");
            ps.setInt(1, item);
            ps.setInt(2, tableno);
            ps.executeUpdate();
            ps.close();
            con.close();

            loadTable();
            clearFields();

        }  catch (Exception e) {

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Error adding record: " + e.getMessage());

        }
    }//GEN-LAST:event_AddActionPerformed

    private void OtableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_OtableMouseClicked
        // TODO add your handling code here:
        int row = Otable.getSelectedRow();

        if (row == -1) {

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Select a row first.");

            return;
        }
        
        Object selectedID = model.getValueAt(row, 0);
        ID.setText(String.valueOf(selectedID));
        Object item = model.getValueAt(row, 1);
        Item.setText(String.valueOf(item));
        Object tableno = model.getValueAt(row, 2);
        Tableno.setText(String.valueOf(tableno));
    }//GEN-LAST:event_OtableMouseClicked

