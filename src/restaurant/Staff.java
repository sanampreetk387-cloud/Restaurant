    private void AddstaffActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AddstaffActionPerformed
        // TODO add your handling code here:
        try {
         int id=Integer.parseInt(ID.getText());
            String name = Name.getText();
            int phone  = Integer.parseInt(Phone.getText());
          String role=Role.getActionCommand();
            int salary = Integer.parseInt(Salary.getText());
             
            if (name.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Name cannot be empty.");
                return;
            }

            Connection con = DBConnection.getConnection();
            PreparedStatement ps = con.prepareStatement(
                "INSERT INTO Staff (ID, Name, Phone,Role,Salary) VALUES (?, ?, ?,?,?)");
            ps.setInt(1, id);
            ps.setString(2, name);
            ps.setInt(3, phone);
             ps.setString(4, role);
              ps.setInt(5, salary);
            ps.executeUpdate();
            ps.close();
            con.close();


            loadTable();

            clearFields();

        }  catch (Exception e) {

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Error adding record: " + e.getMessage());

        }
    }//GEN-LAST:event_AddstaffActionPerformed

    private void DeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteActionPerformed
        // TODO add your handling code here:
          int row = Stable.getSelectedRow();

        if (row == -1) {

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Select a row first.");

            return;
        }
 int confirm = javax.swing.JOptionPane.showConfirmDialog(this,
                "Are you sure you want to delete this record?",
                "Confirm Delete", javax.swing.JOptionPane.YES_NO_OPTION);

        if (confirm != javax.swing.JOptionPane.YES_OPTION) {
            return;
        }

        try {

            // Use the roll_no of the selected row to identify the record
            int selectedID = (int) model.getValueAt(row, 2);

            Connection con = DBConnection.getConnection();
            PreparedStatement ps = con.prepareStatement(
                "DELETE FROM Staff WHERE ID = ?");
            ps.setInt(1, selectedID);
            ps.executeUpdate();
            ps.close();
            con.close();
       

        loadTable();
        clearFields();
    }//GEN-LAST:event_DeleteActionPerformed
catch (Exception e) {

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Error deleting record: " + e.getMessage());

        }
    }                                      
